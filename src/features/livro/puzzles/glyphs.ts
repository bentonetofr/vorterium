/** Desenha um mapa de bits: cada '#' vira um quadrado de `k` pixels. */
export function drawBits(ctx: Ctx, bits: string[], x: number, y: number, color: string, k = 1) {
  ctx.fillStyle = color
  for (let r = 0; r < bits.length; r++) {
    const row = bits[r]
    for (let c = 0; c < row.length; c++) if (row[c] === '#') ctx.fillRect(Math.round(x + c * k), Math.round(y + r * k), k, k)
  }
}

/** Um mapa de bits num canvas próprio (pra usar em botões e listas). */
export function bitsCanvas(bits: string[], color: string, k: number, pad = 0): HTMLCanvasElement {
  const c = document.createElement('canvas')
  c.width = (bits[0].length + pad * 2) * k
  c.height = (bits.length + pad * 2) * k
  const ctx = c.getContext('2d')!
  drawBits(ctx, bits, pad * k, pad * k, color, k)
  return c
}
